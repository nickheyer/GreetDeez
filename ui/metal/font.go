const glyphW, glyphH = 8, 8

func glyph(ch rune) *[8]byte {
	if ch < 32 || ch > 126 {
		ch = '?'
	}
	return &font8x8[ch-32]
}

func TextWidth(s string, scale int) int {
	n := 0
	for range s {
		n++
	}
	return n * glyphW * scale
}

// DrawText draws s at top-left (x, y) with integer scale.
func (f *Frame) DrawText(x, y int, s string, scale int, col uint32) {
	cx := x
	for _, ch := range s {
		f.drawGlyph(cx, y, glyph(ch), scale, col, col)
		cx += glyphW * scale
	}
}

// DrawTextGrad draws s with a vertical top-to-bottom color gradient.
func (f *Frame) DrawTextGrad(x, y int, s string, scale int, top, bottom uint32) {
	cx := x
	for _, ch := range s {
		f.drawGlyph(cx, y, glyph(ch), scale, top, bottom)
		cx += glyphW * scale
	}
}

// DrawTextShadow drops a dark copy behind the text for readability.
func (f *Frame) DrawTextShadow(x, y int, s string, scale int, col, shadow uint32) {
	off := max(1, scale/2)
	f.DrawText(x+off, y+off, s, scale, shadow)
	f.DrawText(x, y, s, scale, col)
}

func (f *Frame) drawGlyph(x, y int, g *[8]byte, scale int, top, bottom uint32) {
	for row := 0; row < glyphH; row++ {
		bits := g[row]
		if bits == 0 {
			continue
		}
		col := top
		if top != bottom {
			col = lerpColor(top, bottom, uint32(row*256/glyphH))
		}
		for bit := 0; bit < glyphW; bit++ {
			if bits&(0x80>>bit) == 0 {
				continue
			}
			f.FillRect(x+bit*scale, y+row*scale, scale, scale, col)
		}
	}
}
